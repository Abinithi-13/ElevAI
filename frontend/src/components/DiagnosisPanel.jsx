import { Sparkles, ShieldAlert, ListChecks, Search } from 'lucide-react';
import { Badge } from './Badges.jsx';
import { CATEGORY_LABELS } from '../utils/constants.js';
import { formatDateTime } from '../utils/format.js';

export default function DiagnosisPanel({ diagnosis }) {
  if (!diagnosis) return null;
  return (
    <div className="rounded-xl border border-brand-200 bg-brand-50/40 p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2 text-brand-700">
          <Sparkles size={18} />
          <span className="text-sm font-bold">AI fault diagnosis</span>
        </div>
        <Badge value={diagnosis.severity} label={`${diagnosis.severity} severity`} />
      </div>

      <h4 className="mt-3 text-lg font-bold text-navy-900">{diagnosis.probableFault}</h4>
      {diagnosis.affectedComponent && <p className="text-sm text-navy-500">Likely component: {CATEGORY_LABELS[diagnosis.affectedComponent] || diagnosis.affectedComponent}</p>}

      <div className="mt-4 grid gap-4 md:grid-cols-2">
        <Section icon={Search} title="Possible causes">
          <ul className="list-disc space-y-1 pl-5">{diagnosis.possibleCauses?.map((c) => <li key={c}>{c}</li>)}</ul>
        </Section>
        <Section icon={ListChecks} title="Recommended maintenance actions">
          <ol className="list-decimal space-y-1 pl-5">{diagnosis.recommendedActions?.map((c) => <li key={c}>{c}</li>)}</ol>
        </Section>
      </div>

      {diagnosis.precautions?.length > 0 && (
        <div className="mt-4 rounded-lg border border-amber-200 bg-amber-50 p-3">
          <div className="mb-1 flex items-center gap-2 text-sm font-bold text-amber-800">
            <ShieldAlert size={16} /> Precautions
          </div>
          <ul className="list-disc space-y-1 pl-5 text-sm text-amber-900">{diagnosis.precautions.map((c) => <li key={c}>{c}</li>)}</ul>
        </div>
      )}
      <p className="mt-3 text-xs text-navy-400">
        Generated by {diagnosis.model} on {formatDateTime(diagnosis.generatedAt)}. AI guidance only. A qualified technician must verify before any repair.
      </p>
    </div>
  );
}

function Section({ icon: Icon, title, children }) {
  return (
    <div>
      <div className="mb-1.5 flex items-center gap-2 text-sm font-bold text-navy-800">
        <Icon size={16} className="text-brand-600" /> {title}
      </div>
      <div className="text-sm text-navy-700">{children}</div>
    </div>
  );
}
