import { useState } from 'react';
import { Info, Sparkles, TrendingUp } from 'lucide-react';
import { Bar, BarChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import api, { getErrorMessage } from '../../api/client.js';
import useApi from '../../hooks/useApi.js';
import { useAuth } from '../../context/AuthContext.jsx';
import PageHeader from '../../components/PageHeader.jsx';
import StatCard from '../../components/StatCard.jsx';
import ChartCard, { NoData } from '../../components/ChartCard.jsx';
import EmptyState from '../../components/EmptyState.jsx';
import { Badge, SourceBadge } from '../../components/Badges.jsx';
import { PageLoader, ErrorState, Spinner } from '../../components/Spinner.jsx';
import { CATEGORY_LABELS } from '../../utils/constants.js';
import { formatDate, formatDateTime } from '../../utils/format.js';

export default function Predictive() {
  const { user } = useAuth();
  const [windowDays, setWindowDays] = useState(180);
  const { data, loading, error, reload } = useApi('/predictive/rule-based', { windowDays });
  const [ai, setAi] = useState({ loading: false, error: '', result: null });

  const runAi = async () => {
    setAi({ loading: true, error: '', result: null });
    try {
      const res = await api.post('/predictive/ai', null, { params: { windowDays } });
      setAi({ loading: false, error: '', result: res.data });
    } catch (err) {
      setAi({ loading: false, error: getErrorMessage(err), result: null });
    }
  };

  return (
    <>
      <PageHeader
        title="Predictive maintenance"
        subtitle="Which components fail most often and where to focus maintenance next."
        actions={
          <select className="input w-44" value={windowDays} onChange={(e) => { setWindowDays(Number(e.target.value)); setAi({ loading: false, error: '', result: null }); }} aria-label="Analysis window">
            <option value={90}>Last 90 days</option><option value={180}>Last 180 days</option><option value={365}>Last 12 months</option>
          </select>
        }
      />
      <div className="mb-6 flex gap-3 rounded-xl border border-navy-200 bg-white p-4 text-sm text-navy-600">
        <Info size={18} className="mt-0.5 shrink-0 text-brand-600" />
        <p>Everything on this page is derived from your recorded complaints and maintenance records. No sensor data is collected, simulated or invented. Results are labelled by source: <strong>rule-based estimates</strong> are plain calculations, <strong>AI predictions</strong> are generated by Gemini from the same records.</p>
      </div>

      {loading ? <PageLoader label="Analyzing maintenance records..." /> : error ? <ErrorState message={error} onRetry={reload} /> : (
        <>
          <section>
            <div className="mb-3 flex flex-wrap items-center gap-3"><h2 className="text-lg font-bold">Failure patterns and priorities</h2><SourceBadge kind="rule" /></div>
            <div className="grid gap-4 sm:grid-cols-3">
              <StatCard icon={TrendingUp} label="Complaints analyzed" value={data.dataSummary.complaintsAnalyzed} tone="navy" hint={`Last ${data.windowDays} days`} />
              <StatCard icon={TrendingUp} label="Maintenance records" value={data.dataSummary.maintenanceRecordsAnalyzed} tone="navy" />
              <StatCard icon={TrendingUp} label="High-priority components" value={data.items.filter((i) => i.priority === 'high').length} tone="red" hint="Across all elevators" />
            </div>

            {data.insufficientData && <div className="mt-4 rounded-lg border border-amber-200 bg-amber-50 p-3 text-sm text-amber-900">Fewer than 5 complaints were recorded in this window, so patterns may not be meaningful yet.</div>}

            {data.items.length === 0 ? (
              <div className="card mt-6"><EmptyState icon={TrendingUp} title="No fault history in this window" message="Once complaints are recorded, failing components and priorities will appear here." /></div>
            ) : (
              <>
                <div className="mt-6 grid gap-6 lg:grid-cols-5">
                  <ChartCard title="Frequently failing components" subtitle="Total faults across all elevators" className="lg:col-span-2">
                    {data.components.length ? (
                      <ResponsiveContainer width="100%" height={Math.max(220, data.components.length * 36)}>
                        <BarChart data={data.components} layout="vertical" margin={{ left: 20 }}>
                          <CartesianGrid strokeDasharray="3 3" stroke="#e4e8f4" horizontal={false} />
                          <XAxis type="number" allowDecimals={false} tick={{ fontSize: 12 }} />
                          <YAxis type="category" dataKey="label" width={130} tick={{ fontSize: 12 }} />
                          <Tooltip />
                          <Bar dataKey="totalFaults" name="Faults" fill="#7437e8" radius={[0, 4, 4, 0]} />
                          <Bar dataKey="highSeverity" name="High or critical" fill="#233159" radius={[0, 4, 4, 0]} />
                        </BarChart>
                      </ResponsiveContainer>
                    ) : <NoData />}
                  </ChartCard>

                  <section className="card lg:col-span-3">
                    <div className="border-b border-navy-100 px-5 py-4"><h3 className="font-bold">Elevator maintenance priority</h3><p className="text-xs text-navy-400">Score from faults, overdue jobs, time since service and availability</p></div>
                    <div className="table-wrap"><table className="table"><thead><tr><th>Elevator</th><th>Faults</th><th>Overdue jobs</th><th>Last service</th><th>Score</th><th>Priority</th></tr></thead><tbody>
                      {data.elevatorPriorities.slice(0, 8).map((e) => (
                        <tr key={e.elevatorId}><td className="font-semibold text-navy-900">{e.elevatorId}<span className="block text-xs font-normal text-navy-400">{e.building}</span></td><td>{e.faults}</td><td>{e.overdueMaintenance}</td><td>{e.lastServiceAt ? `${e.daysSinceService} days ago` : 'Never'}</td><td>{e.score}</td><td><Badge value={e.priority} /></td></tr>
                      ))}
                    </tbody></table></div>
                  </section>
                </div>

                <section className="card mt-6">
                  <div className="border-b border-navy-100 px-5 py-4"><h3 className="font-bold">Component maintenance priorities</h3><p className="text-xs text-navy-400">Ranked by rule-based score. Expected next fault is only estimated when 3 or more faults exist, using the average gap between past faults.</p></div>
                  <div className="table-wrap"><table className="table"><thead><tr><th>Elevator</th><th>Component</th><th>Faults</th><th>Last fault</th><th>Last service</th><th>Avg gap</th><th>Expected next fault</th><th>Score</th><th>Priority</th></tr></thead><tbody>
                    {data.items.slice(0, 12).map((i) => (
                      <tr key={`${i.elevatorId}-${i.component}`}>
                        <td className="font-semibold text-navy-900">{i.elevatorId}</td>
                        <td>{i.componentLabel}<span className="block max-w-xs text-xs text-navy-400">{i.reasons.join('; ')}</span></td>
                        <td>{i.faultCount}</td><td>{formatDate(i.lastFaultAt)}</td>
                        <td>{i.lastServiceAt ? formatDate(i.lastServiceAt) : <span className="text-red-600">None</span>}</td>
                        <td>{i.avgIntervalDays ? `${i.avgIntervalDays} days` : '-'}</td>
                        <td>{i.nextExpectedFault ? formatDate(i.nextExpectedFault) : <span className="text-navy-300">Not enough data</span>}</td>
                        <td>{i.score}</td><td><Badge value={i.priority} /></td>
                      </tr>
                    ))}
                  </tbody></table></div>
                </section>
              </>
            )}
            <p className="mt-3 text-xs text-navy-400">{data.disclaimer}</p>
          </section>

          <section className="mt-10">
            <div className="mb-3 flex flex-wrap items-center justify-between gap-3">
              <div className="flex flex-wrap items-center gap-3"><h2 className="text-lg font-bold">AI prediction</h2><SourceBadge kind="ai" /></div>
              {user.role === 'admin' && <button className="btn-primary" onClick={runAi} disabled={ai.loading || data.items.length === 0}>{ai.loading ? <Spinner size={16} /> : <Sparkles size={16} />} Generate AI prediction</button>}
            </div>
            {user.role !== 'admin' && <p className="text-sm text-navy-500">AI predictions are generated by administrators.</p>}
            {ai.loading && <div className="card card-pad flex items-center gap-3 text-sm text-brand-700" role="status"><Spinner /> Gemini is reviewing your maintenance statistics. This can take up to a minute.</div>}
            {ai.error && <div role="alert" className="rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-700">{ai.error}</div>}
            {ai.result && (
              <div className="card card-pad space-y-5">
                <p className="text-sm text-navy-800">{ai.result.summary}</p>
                <div className="grid gap-4 md:grid-cols-2">
                  {ai.result.predictions.map((p) => (
                    <div key={`${p.elevatorId}-${p.component}`} className="rounded-xl border border-brand-200 bg-brand-50/30 p-4">
                      <div className="flex flex-wrap items-center justify-between gap-2"><p className="font-bold text-navy-900">{p.elevatorId} - {CATEGORY_LABELS[p.component]}</p><Badge value={p.riskLevel} label={`${p.riskLevel} risk`} /></div>
                      <p className="mt-2 text-sm text-navy-700">{p.reasoning}</p>
                      <p className="mt-2 text-sm"><span className="font-semibold">Recommended:</span> {p.recommendedAction}</p>
                      <p className="mt-2 text-xs text-navy-400">AI confidence: {p.confidence}</p>
                    </div>
                  ))}
                </div>
                {ai.result.dataLimitations.length > 0 && (
                  <div className="rounded-lg bg-navy-50 p-3 text-sm text-navy-700"><p className="mb-1 font-semibold">Data limitations</p><ul className="list-disc space-y-0.5 pl-5">{ai.result.dataLimitations.map((l) => <li key={l}>{l}</li>)}</ul></div>
                )}
                <p className="text-xs text-navy-400">{ai.result.disclaimer} Generated by {ai.result.model} on {formatDateTime(ai.result.generatedAt)} from {ai.result.basedOn.complaintsAnalyzed} complaints.</p>
              </div>
            )}
          </section>
        </>
      )}
    </>
  );
}
